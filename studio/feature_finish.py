@router.post("/run")
def run_post(b: dict = None):
    """One effect on one clip, in the background: poll /api/finish/jobs/{job}. Only effects with a proof on record and their files in ComfyUI are run."""
    b = b or {}; o = options(b); clip = clip_path(b.get("clip"))
    row = next(r for r in listing() if r["id"] == o["effect"])
    if not row["comfy_up"]: raise HTTPException(503, "ComfyUI is not reachable, so nothing can run.")
    if row["missing"]: raise HTTPException(409, f"{row['label']} needs files ComfyUI doesn't list: " + ", ".join(row["missing"]))
    if not row["proven"]: raise HTTPException(409, f"{row['label']} has no proof render on record yet, so the page doesn't offer it.")
    why = vram_problem(o["effect"])
    if why: raise HTTPException(409, why)
    info = probe(clip)
    if info["seconds"] and info["seconds"] < 0.5: raise HTTPException(400, f"{clip.name} is too short: LTX needs at least 9 frames.")
    jid = "fin-" + uuid.uuid4().hex[:10]
    rec = {"job": jid, "status": "running", "step": "starting", "started": time.time(), "clip": clip.name, "clip_info": info, "options": o}
    with _lock: JOBS[jid] = rec
    threading.Thread(target=run_job, args=(rec, clip, o), daemon=True, name=jid).start(); return rec


