def probe(p, run=subprocess.run) -> dict:
    """{width, height, seconds, fps, frames, pix_fmt, color_primaries, color_transfer, bits} of the first video stream, from ffprobe."""
    r = run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height,r_frame_rate,nb_frames,pix_fmt,color_primaries,color_transfer,color_space,bits_per_raw_sample,codec_name,profile:format=duration", "-of", "json", str(p)], capture_output=True, text=True, timeout=30)
    try: d = json.loads(r.stdout or "{}")
    except ValueError: d = {}
    s = (d.get("streams") or [None])[0]
    if not s: raise HTTPException(400, f"{Path(p).name} isn't a readable video")
    num, _, den = str(s.get("r_frame_rate") or "24/1").partition("/")
    try: fps = float(num) / float(den or 1)
    except (ValueError, ZeroDivisionError): fps = 24.0
    try: secs = float((d.get("format") or {}).get("duration") or 0)
    except ValueError: secs = 0.0
    pf = s.get("pix_fmt") or ""; bits = 12 if "12" in pf else 10 if "10" in pf else 16 if "16" in pf or "48" in pf else 8
    return {"width": int(s.get("width") or 0), "height": int(s.get("height") or 0), "seconds": round(secs, 3), "fps": round(fps, 3), "frames": int(s["nb_frames"]) if str(s.get("nb_frames") or "").isdigit() else None,
            "pix_fmt": pf, "bits": bits, "codec": s.get("codec_name"), "profile": s.get("profile"), "color_primaries": s.get("color_primaries"), "color_transfer": s.get("color_transfer"), "color_space": s.get("color_space")}


