PEAK_GIB = {"restore": 40, "deblur": 40, "decompress": 40, "colorize": 40, "upscale": 44, "hdr": 44}   # declared before any proof; finish_proof.json's measured peak wins when there is one


def vram_problem(effect, c=None, free=None) -> str:
    """'' when the card has room for this effect above the 4 GB floor, or when ComfyUI is on another machine (its card isn't ours to read)."""
    c = c or Comfy()
    if urllib.parse.urlparse(c.url).hostname not in ("127.0.0.1", "localhost", "::1"): return ""
    from psn import instances as I
    measured = ((proof().get("effects") or {}).get(effect) or {}).get("peak_vram_gib")
    peak = float(measured or PEAK_GIB[effect])
    try: f = (free or I.free_vram_gb)()
    except Exception: return ""
    if f is None or f < peak + I.FLOOR_GB: return f"only {f or 0:.1f} GB of video memory is free; {EFFECTS[effect]['label']} peaks near {peak:.0f} GB and the card keeps {I.FLOOR_GB:g} GB spare. Nothing was stopped to make room; try again when the card is quieter."
    return ""


def options(b) -> dict:
    """The request, checked. Words go into a prompt, so they are trimmed and capped; numbers are clamped."""
    effect = str(b.get("effect") or "")
    if effect not in EFFECTS: raise HTTPException(400, "pick one of the listed effects")
    try: seconds = int(b.get("seconds") or 4)
    except (TypeError, ValueError): raise HTTPException(400, "seconds must be a whole number") from None
    if seconds not in SECONDS: raise HTTPException(400, f"seconds must be one of {', '.join(map(str, SECONDS))}")
    quality = str(b.get("quality") or "trained")
    if quality not in QUALITY: raise HTTPException(400, "quality must be trained or full")
    seed = b.get("seed"); seed = 42 if seed in (None, "") else int(seed)
    strength = b.get("strength"); strength = None if strength in (None, "") else float(strength)
    clip = lambda k: re.sub(r"\s+", " ", str(b.get(k) or "")).strip()[:400]
    return {"effect": effect, "seconds": seconds, "quality": quality, "seed": seed, "strength": strength, "scene": clip("scene"), "colors": clip("colors")}


def hdr_masters(stem, hist, c, out_root=None) -> dict:
    """After an HDR run: the ProRes 4444 master from the 16-bit HLG frames, a zip of the EXR frames, and what ffprobe and OpenEXR say about each. Needs ComfyUI's output folder on this machine."""
    from studio import finish_measure as M
    root = Path(out_root or paths.output_dir(True)); png, exr = root / "finish" / "hlg16" / stem, root / "finish" / "hdr_exr" / stem
    hlg = outputs(hist, "save")[0]; hlg_path = root / hlg.get("subfolder", "") / hlg["filename"]
    if not png.is_dir() or not exr.is_dir(): return {"note": "The HLG master is ready. The EXR frames and the ProRes master are written by ComfyUI on its own machine, so they are in its output folder, not here."}
    master = root / "finish" / f"{stem}_prores4444_hlg.mov"; M.prores_from_png16(png, master)
    z = shutil.make_archive(str(root / "finish" / f"{stem}_exr_acescg_half"), "zip", exr)
    rep = M.hdr_report(hlg_path, exr, master); shutil.rmtree(png, ignore_errors=True)
    return {"prores": _view(master), "exr_zip": _view(Path(z)), "report": rep}


def run_job(rec, clip, o, c=None):
    """Clip -> ComfyUI -> result, filling rec as it goes; never raises."""
    c = c or Comfy(); t0 = time.time()
    try:
        info = rec["clip_info"]; stem = f"{o['effect']}_{time.strftime('%Y%m%d_%H%M%S')}_{rec['job'][-6:]}"
        rec["step"] = "sending the clip to ComfyUI"; name = c.upload(clip)
        vals = values(o["effect"], info, seconds=o["seconds"], scene=o["scene"], colors=o["colors"], seed=o["seed"], quality=o["quality"], strength=o["strength"], video=name, stem=stem)
        rec.update(step=f"LTX-2.5 with the {EFFECTS[o['effect']]['label']} IC-LoRA", size=[vals["width"], vals["height"]], frames=vals["frames"], prompt=vals.get("prompt") or "")
        with _gate: h = c.run(graph(o["effect"], vals, prefix=f"finish/{stem}"))
        it = outputs(h, "save")[0]; files = {"video": {**it, "type": it.get("type", "output"), "url": "/api/view?" + urllib.parse.urlencode({"filename": it["filename"], "subfolder": it.get("subfolder", ""), "type": it.get("type", "output")})}}
        if o["effect"] == "hdr":
            sv = outputs(h, "saves")[0]; files["preview"] = {**sv, "url": "/api/view?" + urllib.parse.urlencode({"filename": sv["filename"], "subfolder": sv.get("subfolder", ""), "type": sv.get("type", "output")})}
            rec["step"] = "writing the ProRes master and packing the EXR frames"; files |= hdr_masters(stem, h, c)
        rec.update(status="done", step="", files=files, seconds=round(time.time() - t0, 1), ai_generated=True)
    except Exception as e: rec.update(status="error", step="", error=f"{e}"[:700])


