        names |= set(oi[1].get("options") or []) if len(oi) > 1 and isinstance(oi[1], dict) else set(oi[0] if isinstance(oi[0], list) else [])
        em = c.get("/object_info/LTXVLoadConditioning", 10)["LTXVLoadConditioning"]["input"]["required"]["file_name"]
