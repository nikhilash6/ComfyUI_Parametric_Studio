class Comfy:
    """The few calls these graphs need. Tests pass a fake with the same methods."""
    def __init__(self, url=None): self.url = (url or os.environ.get("FINISH_COMFYUI_URL") or os.environ.get("COMFYUI_URL") or "http://127.0.0.1:8200").rstrip("/")

    def get(self, path, timeout=60): return json.load(urllib.request.urlopen(self.url + path, timeout=timeout))

    def upload(self, path) -> str:
        p = Path(path); b = uuid.uuid4().hex
        body = (f'--{b}\r\nContent-Disposition: form-data; name="image"; filename="{p.name}"\r\nContent-Type: application/octet-stream\r\n\r\n').encode() + p.read_bytes() + (f'\r\n--{b}\r\nContent-Disposition: form-data; name="overwrite"\r\n\r\ntrue\r\n--{b}--\r\n').encode()
        return json.loads(urllib.request.urlopen(urllib.request.Request(self.url + "/upload/image", data=body, headers={"Content-Type": f"multipart/form-data; boundary={b}"}), timeout=300).read())["name"]

    def run(self, g, timeout=3600, tick=None) -> dict:
        try: pid = json.loads(urllib.request.urlopen(urllib.request.Request(self.url + "/prompt", json.dumps({"prompt": g, "client_id": "ltx-finish"}).encode(), {"Content-Type": "application/json"}), timeout=120).read())["prompt_id"]
        except urllib.error.HTTPError as e: raise RuntimeError("ComfyUI refused the graph: " + e.read().decode(errors="replace")[:600]) from None
        t0 = time.time()
        while time.time() - t0 < timeout:
            time.sleep(2)
            if tick: tick()
            h = self.get(f"/history/{pid}").get(pid)
            if not h: continue
            st = h.get("status") or {}
            if st.get("status_str") == "error":
                raise RuntimeError("ComfyUI stopped: " + next((i.get("exception_message", "") for k, i in st.get("messages", []) if k == "execution_error"), "").strip()[:500])
            if st.get("completed"): return h
        self.cancel(); raise RuntimeError(f"timed out after {timeout} s")

    def cancel(self):
        try: urllib.request.urlopen(urllib.request.Request(self.url + "/interrupt", b"{}", {"Content-Type": "application/json"}), timeout=10)
        except Exception: pass

    def free(self):
        try: urllib.request.urlopen(urllib.request.Request(self.url + "/free", json.dumps({"unload_models": True, "free_memory": True}).encode(), {"Content-Type": "application/json"}), timeout=60)
        except Exception: pass

    def fetch(self, item, dest: Path) -> Path:
        q = urllib.parse.urlencode({"filename": item["filename"], "subfolder": item.get("subfolder", ""), "type": item.get("type", "output")})
        dest.parent.mkdir(parents=True, exist_ok=True); dest.write_bytes(urllib.request.urlopen(f"{self.url}/view?{q}", timeout=300).read()); return dest


