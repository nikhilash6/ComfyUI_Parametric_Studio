def _al(x, step=32): return max(step, int(round(x / step)) * step)


def canvas(width, height, longest, step=32):
    """The working size: the clip's shape, its longest side at most `longest`, both sides a multiple of `step`."""
    k = min(1.0, longest / max(width, height)); return _al(width * k, step), _al(height * k, step)


def ltx_frames(seconds, have_seconds=None, fps=24):
    """LTX wants 8k+1 frames; never more than the clip has."""
    k = max(1, round(seconds * fps / 8))
    if have_seconds is not None: k = min(k, max(1, math.floor((math.floor(have_seconds * fps) - 1) / 8)))
    return 8 * k + 1


