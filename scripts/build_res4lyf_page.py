#!/usr/bin/env python3
"""Writes studio/web/res4lyf_data.js from a checkout of ClownsharkBatwing/RES4LYF.

Static parsing only: the pack's code is read, never imported or run, and none of it is copied.
What lands in the page is facts about it: sampler and node names, counts, and example file names.
Usage: build_res4lyf_page.py /path/to/RES4LYF
"""
import ast
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "studio" / "web"
OUT = WEB / "res4lyf_data.js"
FAMILIES = (
    ("multistep", "Multistep"),
    ("exponential", "Exponential"),
    ("hybrid", "Hybrid"),
    ("linear", "Linear"),
    ("diag_implicit", "Diagonally implicit"),
    ("fully_implicit", "Fully implicit"),
)


def write_nodes():
    """Joins the notes from reading each node's source with what happened when it ran in a graph."""
    notes = json.loads((ROOT / "docs" / "res4lyf" / "node_notes.json").read_text())
    check = json.loads((WEB / "res4lyf_node_check.json").read_text()) if (WEB / "res4lyf_node_check.json").exists() else {}
    rows = []
    for n in notes:
        c = check.get(n["node"], {})
        rows.append({"n": n["node"], "g": n["group"], "d": n["does"], "u": n.get("use", ""), "src": n["source"], "s": c.get("state", "untested"), "e": c.get("detail", ""), "t": c.get("thumb", ""), "j": c.get("graph", ""), "w": c.get("wired", "")})
    (WEB / "res4lyf_nodes.js").write_text("// Generated by scripts/build_res4lyf_page.py. Notes are ours, written from reading each node's source; no code from the pack.\nexport const NODES = " + json.dumps(rows, ensure_ascii=False) + ";\n")


def write_renders():
    """Smaller copies of the full renders for the page, and their captions."""
    from PIL import Image
    d = WEB / "res4lyf_renders"
    res = json.loads((d / "results.json").read_text()) if (d / "results.json").exists() else {}
    rows = []
    for key, r in res.items():
        if not r.get("ok") or "family" not in r:
            continue
        moving = (d / f"{key}.webp").exists()
        if not moving:
            im = Image.open(d / f"{key}.png").convert("RGB")
            im.thumbnail((768, 768))
            im.save(d / f"{key}.jpg", quality=82)
        rows.append({"key": key, "family": r["family"], "name": r["name"], "what": r["what"], "seed": r["seed"], "steps": r["steps"], "cfg": r["cfg"], "size": r["size"], "src": f"res4lyf_renders/{key}.{'webp' if moving else 'jpg'}", "graph": r["graph"]})
    (WEB / "res4lyf_gallery.js").write_text("// Generated by scripts/build_res4lyf_page.py from our own renders.\nexport const GALLERY = " + json.dumps(rows) + ";\n")


def assigned(path, name):
    for n in ast.parse(path.read_text(errors="ignore")).body:
        if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == name:
            return n.value
    raise SystemExit(f"{name} not found in {path}")


def node_names(path):
    """Keys of every literal NODE_CLASS_MAPPINGS dict in a file, including .update({...}) calls."""
    names = []
    for n in ast.walk(ast.parse(path.read_text(errors="ignore"))):
        d = None
        if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "NODE_CLASS_MAPPINGS" for t in n.targets):
            d = n.value
        elif isinstance(n, ast.Call) and getattr(n.func, "attr", "") == "update" and getattr(n.func.value, "id", "") == "NODE_CLASS_MAPPINGS" and n.args:
            d = n.args[0]
        if isinstance(d, ast.Dict):
            names += [k.value for k in d.keys if isinstance(k, ast.Constant)]
    return sorted(set(names), key=str.lower)


def build(repo):
    git = lambda *a: subprocess.run(["git", "-C", str(repo), *a], capture_output=True, text=True, check=True).stdout.strip()
    folders = ast.literal_eval(assigned(repo / "beta" / "rk_coefficients_beta.py", "RK_SAMPLER_NAMES_BETA_FOLDERS"))
    by_family = {k: [s.split("/")[-1] for s in folders if s.startswith(k + "/")] for k, _ in FAMILIES}
    noise = assigned(repo / "beta" / "noise_classes.py", "NOISE_GENERATOR_CLASSES")
    modes = ast.literal_eval(assigned(repo / "beta" / "rk_noise_sampler_beta.py", "NOISE_MODE_NAMES"))
    return {
        "commit": git("log", "-1", "--format=%h"),
        "sha": git("rev-parse", "HEAD"),
        "commitDate": git("log", "-1", "--format=%ad", "--date=short"),
        "families": [{"key": k, "label": label, "samplers": by_family[k]} for k, label in FAMILIES],
        "nodes": {
            "core": node_names(repo / "__init__.py"),
            "beta": node_names(repo / "beta" / "__init__.py"),
            "legacy": node_names(repo / "legacy" / "__init__.py"),
        },
        "noiseTypes": sorted(k.value for k in noise.keys),
        "noiseModes": len(modes),
        "examples": sorted(p.stem for p in (repo / "example_workflows").glob("*.json")),
    }


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = build(pathlib.Path(sys.argv[1]))
    write_nodes()
    write_renders()
    OUT.write_text("// Generated by scripts/build_res4lyf_page.py from a read of the RES4LYF source. Names and counts only, no code from the pack.\nexport const DATA = " + json.dumps(data, indent=1) + ";\n")
    print(OUT, sum(len(f["samplers"]) for f in data["families"]), "samplers,", sum(map(len, data["nodes"].values())), "node names")
